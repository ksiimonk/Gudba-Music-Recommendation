def replace_para_text(doc, old, new):
    for p in doc.paragraphs:
        if p.text.strip() == old.strip():
            for run in p.runs:
                run.text = ''
            if p.runs:
                p.runs[0].text = new
            else:
                p.add_run(new)
            return True
    return False

def replace_para_text_containing(doc, substr, new):
    for p in doc.paragraphs:
        if substr in p.text:
            for run in p.runs:
                run.text = ''
            if p.runs:
                p.runs[0].text = new
            else:
                p.add_run(new)
            return True
    return False

